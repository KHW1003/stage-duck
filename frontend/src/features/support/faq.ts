/** 질문·답에 검색어가 들어간 것만 남긴다 (공백 무시, 대소문자 무시). 빈 그룹은 뺀다 */
export function searchFaq(groups: FaqGroup[], query: string): FaqGroup[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return groups;
  return groups
    .map((g) => ({ ...g, items: g.items.filter((it) => words.every((w) => `${it.q} ${it.a}`.toLowerCase().includes(w))) }))
    .filter((g) => g.items.length > 0);
}
